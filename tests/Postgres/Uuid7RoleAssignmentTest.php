<?php

declare(strict_types=1);

use Illuminate\Database\Migrations\Migration;
use Illuminate\Database\QueryException;
use Illuminate\Database\Schema\Blueprint;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use RobinsonRyan\Permixion\Facades\Permixion;
use RobinsonRyan\Permixion\Tests\Fixtures\Uuid7User;

/*
|--------------------------------------------------------------------------
| Roles and permissions with database-generated UUIDv7 keys
|--------------------------------------------------------------------------
|
| Taxon 0.5.0 changed two things this package sits directly on top of: tag keys
| are generated by PostgreSQL's uuidv7() column default instead of by PHP, and a
| tag attribute assigned to an unsaved model is held until the model has a key.
| Permixion writes through the `tags()` relation rather than Taxon's magic tag
| attributes, so neither change should be visible here — and "should" is not
| evidence, hence this file.
|
| It needs `tags` and `taggables` built in uuid7 mode, which the rest of the
| suite does not use, so it works on its own connection against a real
| PostgreSQL server and skips — loudly — where none is reachable. uuidv7() as a
| column default needs PostgreSQL 18+; SQLite cannot express it at all, which is
| why this file cannot live on the shared in-memory connection.
|
*/

const UUID7_CONNECTION = 'pgsql_permixion_uuid7';

/** @return array<string, mixed> */
function uuid7ConnectionConfig(): array
{
    return [
        'driver' => 'pgsql',
        'host' => env('PGHOST', 'db'),
        'port' => env('PGPORT', '5432'),
        'database' => env('PGDATABASE', 'db'),
        'username' => env('PGUSER', 'db'),
        'password' => env('PGPASSWORD', 'db'),
        'charset' => 'utf8',
        'prefix' => '',
        'prefix_indexes' => true,
        'search_path' => 'public',
        'sslmode' => 'prefer',
    ];
}

function dropUuid7Schema(): void
{
    $schema = Schema::connection(UUID7_CONNECTION);

    $schema->dropIfExists('uuid7_users');
    $schema->dropIfExists('taggables');
    $schema->dropIfExists('tags');
}

/**
 * Build a full uuid7 install: Taxon's own tables, run from its published
 * migrations, plus a uuid-keyed consumer table that takes its key from the
 * database the same way.
 */
function migrateUuid7Schema(): void
{
    config()->set('taxon.id_type', 'uuid7');
    config()->set('database.default', UUID7_CONNECTION);

    $files = glob(__DIR__.'/../../vendor/robinsonryan/taxon/database/migrations/*.php');
    $files = $files === false ? [] : $files;
    sort($files);

    foreach ($files as $file) {
        $migration = require $file;

        if ($migration instanceof Migration) {
            $migration->up();
        }
    }

    Schema::connection(UUID7_CONNECTION)->create('uuid7_users', function (Blueprint $table): void {
        $table->uuid('id')->primary()->default(DB::raw('uuidv7()'));
        $table->string('name');
        $table->string('email');
        $table->timestamps();
    });
}

function pivotRowsFor(Uuid7User $user): ?object
{
    return DB::connection(UUID7_CONNECTION)->table('taggables')
        ->where('taggable_id', $user->getKey())
        ->first();
}

beforeEach(function (): void {
    config()->set('database.connections.'.UUID7_CONNECTION, uuid7ConnectionConfig());

    try {
        DB::connection(UUID7_CONNECTION)->getPdo();
    } catch (Throwable $e) {
        $this->markTestSkipped(
            'No PostgreSQL server reachable ('.$e->getMessage().'). Run this suite inside DDEV.'
        );
    }

    dropUuid7Schema();
    migrateUuid7Schema();

    $this->user = Uuid7User::create([
        'name' => 'Uuid User',
        'email' => 'uuid7@example.com',
    ]);
});

afterEach(function (): void {
    dropUuid7Schema();

    // migrateUuid7Schema() repoints the default connection and the key type;
    // hand both back, or the next test in the process builds its fixtures on
    // PostgreSQL in uuid7 mode.
    config()->set('database.default', 'testing');
    config()->set('taxon.id_type', 'incrementing');
});

describe('the keys come from the database', function (): void {
    it('gives a role tag a database-generated uuid7 key', function (): void {
        $role = Permixion::createRole('shop_manager');

        expect($role->tag()->getKey())->toBeUuidV7();
    });

    it('gives a permission tag a database-generated uuid7 key', function (): void {
        $permission = Permixion::createPermission('work_order.assign');

        expect($permission->tag()->getKey())->toBeUuidV7();
    });

    /*
     * The decisive one: take the column default away and role creation must
     * fail. Anything still minting a key in PHP would sail straight through.
     */
    it('generates nothing in PHP — without the column default, creating a role fails', function (): void {
        DB::connection(UUID7_CONNECTION)->statement('alter table tags alter column id drop default');

        expect(fn () => Permixion::createRole('shop_manager'))->toThrow(QueryException::class);
    });

    it('gives the pivot row its own database-generated key', function (): void {
        Permixion::createRole('shop_manager');
        $this->user->assignRole('shop_manager');

        expect(pivotRowsFor($this->user)?->id)->toBeUuidV7();
    });
});

describe('role and permission writes against uuid keys', function (): void {
    it('assigns a role to a saved user and reads it back', function (): void {
        Permixion::createRole('shop_manager');

        $this->user->assignRole('shop_manager');

        expect($this->user->hasRole('shop_manager'))->toBeTrue()
            ->and($this->user->getRoleNames())->toContain('shop_manager');
    });

    it('points the pivot row at the user, keyed by uuid', function (): void {
        Permixion::createRole('shop_manager');

        $this->user->assignRole('shop_manager');

        $pivot = pivotRowsFor($this->user);

        expect($pivot)->not->toBeNull()
            ->and($pivot->taggable_id)->toBe($this->user->getKey())
            ->and($pivot->taggable_type)->toBe(Uuid7User::class);
    });

    it('grants a permission through a role', function (): void {
        Permixion::createPermission('work_order.assign');
        Permixion::createRole('technician', ['work_order.assign']);

        $this->user->assignRole('technician');

        expect($this->user->hasPermissionTo('work_order.assign'))->toBeTrue()
            ->and($this->user->hasPermissionTo('work_order.close'))->toBeFalse();
    });

    it('grants a permission directly', function (): void {
        Permixion::createPermission('settings.update');

        $this->user->givePermissionTo('settings.update');

        expect($this->user->hasPermissionTo('settings.update'))->toBeTrue();
    });

    it('removes a role again', function (): void {
        Permixion::createRole('shop_manager');
        $this->user->assignRole('shop_manager');

        $this->user->removeRole('shop_manager');

        expect($this->user->hasRole('shop_manager'))->toBeFalse()
            ->and(pivotRowsFor($this->user))->toBeNull();
    });
});

describe('a user that has not been saved yet', function (): void {
    /*
     * Taxon 0.5.0 defers a *tag attribute* assigned to an unsaved model until it
     * has a key. Permixion assigns roles through the `tags()` relation instead,
     * which that deferral does not cover, so the pivot write still needs a key
     * up front. Pinned here because it is the one behaviour a reader might
     * assume 0.5.0 changed: it did not, and it fails loudly rather than
     * silently dropping a grant.
     */
    it('refuses a role assignment rather than writing a keyless pivot row', function (): void {
        Permixion::createRole('shop_manager');

        $unsaved = new Uuid7User(['name' => 'Unsaved', 'email' => 'unsaved@example.com']);

        expect(fn (): Uuid7User => $unsaved->assignRole('shop_manager'))->toThrow(QueryException::class)
            ->and(DB::connection(UUID7_CONNECTION)->table('taggables')->count())->toBe(0);
    });

    it('grants the role once the user is saved', function (): void {
        Permixion::createRole('shop_manager');

        $user = new Uuid7User(['name' => 'Saved Later', 'email' => 'later@example.com']);
        $user->save();
        $user->assignRole('shop_manager');

        expect($user->hasRole('shop_manager'))->toBeTrue()
            ->and($user->getKey())->toBeUuidV7();
    });
});
